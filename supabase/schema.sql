create table if not exists public.weather_readings (
  id bigint generated by default as identity primary key,
  temperature numeric not null,
  humidity numeric not null,
  pressure numeric,
  weather_status text,
  device_id text,
  created_at timestamptz not null default now()
);

create index if not exists weather_readings_created_at_idx
  on public.weather_readings (created_at desc);

alter table public.weather_readings enable row level security;

grant usage on schema public to anon, authenticated;
grant select, insert on table public.weather_readings to anon, authenticated;
grant usage, select on sequence public.weather_readings_id_seq to anon, authenticated;

drop policy if exists "Public can read weather readings" on public.weather_readings;
create policy "Public can read weather readings"
  on public.weather_readings
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can insert weather readings" on public.weather_readings;
create policy "Public can insert weather readings"
  on public.weather_readings
  for insert
  to anon, authenticated
  with check (true);

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'weather_readings'
  ) then
    alter publication supabase_realtime add table public.weather_readings;
  end if;
end
$$;